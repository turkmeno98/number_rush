"""Extract operator/region DEF-code sets from a pinned, dated public registry snapshot.

No third-party code is executed. The TypeScript file only supplies JSON data literals.
Only three-digit codes are retained; subscriber ranges are NOT used by the game.
"""
import hashlib
import json
import re
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "analysis/phone_catalog_sources/mobile.ts"
COMMIT = "7687c22cfc3b5243c15ee107a00b1af5b0d4ebe5"
INNS = {"7713076301": "beelink", "7740000076": "mobitel", "7812014560": "megalink", "7743895280": "telenova"}
CITIES = {
    "Москва": ("city_moscow", "Москва", 10000),
    "Санкт-Петербург": ("city_spb", "Санкт-Петербург", 10000),
    "Новосибирская область": ("city_novosibirsk", "Новосибирск", 7500),
    "Свердловская область": ("city_ekaterinburg", "Екатеринбург", 7500),
    "Республика Татарстан": ("city_kazan", "Казань", 7500),
    "Красноярский край": ("city_krasnoyarsk", "Красноярск", 7500),
    "Нижегородская область": ("city_nizhny_novgorod", "Нижний Новгород", 7500),
    "Челябинская область": ("city_chelyabinsk", "Челябинск", 7500),
    "Республика Башкортостан": ("city_ufa", "Уфа", 7500),
    "Краснодарский край": ("city_krasnodar", "Краснодар", 7500),
    "Самарская область": ("city_samara", "Самара", 7500),
    "Ростовская область": ("city_rostov", "Ростов-на-Дону", 7500),
    "Омская область": ("city_omsk", "Омск", 7500),
    "Воронежская область": ("city_voronezh", "Воронеж", 7500),
    "Пермский край": ("city_perm", "Пермь", 7500),
    "Волгоградская область": ("city_volgograd", "Волгоград", 7500),
}


def extract(text, name):
    return json.loads(re.search(rf"^export const {name}.*?= (.*);$", text, re.M).group(1))


def build():
    text = SOURCE.read_text(encoding="utf-8-sig")
    updated = re.search(r"UPDATED: string = '([^']+)'", text).group(1)
    operators, places, encoded = (extract(text, n) for n in ("OPERATORS", "PLACES", "RANGES"))
    pool = defaultdict(lambda: defaultdict(set))
    previous, ranges = -1, 0
    for entry in encoded.split(";"):
        gap, length, operator, place = (int(v, 36) for v in entry.split(","))
        start = previous + 1 + gap
        end = start + length
        assert start > previous and end >= start
        previous = end
        inn = operators[operator][0]
        if inn not in INNS:
            continue
        raw = places[place].split("|")[-1]
        regions = raw.replace("Город Москва", "Москва").replace("Город Санкт-Петербург", "Санкт-Петербург").split(", ")
        codes = {str(code) for code in range(start // 10_000_000, end // 10_000_000 + 1)}
        assert all(re.fullmatch(r"9\d\d", code) for code in codes)
        for region in regions:
            pool[region][INNS[inn]].update(codes)
        ranges += 1
    result = []
    for region in sorted(pool):
        codes = {op: sorted(values) for op, values in sorted(pool[region].items())}
        if region not in ("Москва", "Санкт-Петербург"):
            result.append({"Id": "region_" + hashlib.sha1(region.encode()).hexdigest()[:12], "Name": region,
                           "Price": 5000, "Kind": "Region", "SourceRegion": region, "Codes": codes})
        if region in CITIES:
            key, name, price = CITIES[region]
            result.append({"Id": key, "Name": name, "Price": price, "Kind": "City", "SourceRegion": region, "Codes": codes})
    result.sort(key=lambda r: (r["Id"] != "city_moscow", r["Id"] != "city_spb", r["Name"]))
    assert len({r["Id"] for r in result}) == len(result)
    assert {r["Name"] for r in result if r["Kind"] == "City"} == {v[1] for v in CITIES.values()}
    counts = {op: sum(op in r["Codes"] for r in result) for op in INNS.values()}
    assert min(counts.values()) >= 60
    metadata = {"snapshot_date": updated, "retrieved_on": "2026-11-15", "source_commit": COMMIT,
                "source_url": f"https://github.com/MrProLopstar/phoneoperator/blob/{COMMIT}/src/data/mobile.ts",
                "upstream": "https://opendata.digital.gov.ru/downloads/DEF-9xx.csv",
                "source_sha256": hashlib.sha256(SOURCE.read_bytes()).hexdigest(), "ranges_read": ranges,
                "offer_counts": counts, "region_count": len(result),
                "caveat": "Registry-derived snapshot, not a live MNP lookup. Cities share their subject's code pool. Seven digits are fictional game combinations."}
    output = ["-- Generated by tools/build_region_catalog.py. See docs/PHONE_CODES.md for provenance.",
              "local Catalog = {}", f'Catalog.SnapshotDate = "{updated}"', "Catalog.Regions = {"]
    quote = lambda s: json.dumps(s, ensure_ascii=False)
    for row in result:
        parts = [f'{key} = {quote(row[key])}' for key in ("Id", "Name", "Kind", "SourceRegion")]
        parts.append(f'Price = {row["Price"]}')
        code_lua = ", ".join(f'{op} = {{{", ".join(quote(c) for c in codes)}}}' for op, codes in row["Codes"].items())
        parts.append("Codes = {" + code_lua + "}")
        output.append("\t{" + ", ".join(parts) + "},")
    output += ["}", "return Catalog", ""]
    (ROOT / "src/ReplicatedStorage/RegionCatalog.lua").write_text("\n".join(output), encoding="utf-8")
    (ROOT / "analysis/phone_catalog_sources/catalog_manifest.json").write_text(json.dumps(metadata, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(metadata, ensure_ascii=False))


if __name__ == "__main__":
    build()
